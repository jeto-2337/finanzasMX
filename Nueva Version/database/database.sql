CREATE DATABASE FINANZAS_MX;
CREATE TABLE NAME_PROJECT(
    ID MEDIUMINT AUTO_INCREMENT,
    NAME CHAR(255),
    PRIMARY KEY(ID)
);

CREATE TABLE pagos (
    id INT AUTO_INCREMENT PRIMARY KEY,
    user_id INT,
    monto INT,
    estado VARCHAR(50),
    stripe_id VARCHAR(255),
    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE USERS (
    ID MEDIUMINT AUTO_INCREMENT,
    USER CHAR(255),
    EMAIL CHAR(255),
    PRIMARY KEY(ID)
);


CREATE TABLE GASTOS(
    ID MEDIUMINT AUTO_INCREMENT,
    EMAIL CHAR(255),
    MONTO CHAR(255),
    DESCRIPCION CHAR(255),
    CATEGORIA CHAR()255,
    FECHA CHAR(255),
    PRIMARY KEY(ID)
    
);